_CONCLUSION_SCHEMA = {
    "type": "object",
    "properties": {"aiConclusion": {"type": "string"}},
    "required": ["aiConclusion"],
}


def _parse_iso(s: str | None) -> datetime | None:
    if not s:
        return None
    if s.endswith("Z"):
        s = s[:-1] + "+00:00"
    try:
        dt = datetime.fromisoformat(s)
    except ValueError:
        return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt


async def assemble_report(db: AsyncSession, voyage: Voyage) -> VoyageReport:
    voyage_out = _voyage_to_out(voyage)
    events = await list_events(db, voyage.id)
    alerts = await list_alerts(db, voyage.id)
    eta_series = await list_eta_series(db, voyage.id)
    milestones = await list_milestones(db, voyage.id)
    attribution = await compute_attribution(db, voyage)

    live = await compute_live_snapshot(db, voyage)
    final_risk_score = voyage.final_risk_score or live.riskScore

    # Duration metrics
    pd = _parse_iso(voyage.planned_departure)
    pa = _parse_iso(voyage.planned_arrival) or pd
    ad = _parse_iso(voyage.actual_departure) or pd
    aa = _parse_iso(voyage.actual_arrival) or datetime.now(tz=timezone.utc)
    duration_planned_min = max(60, int(((pa - pd).total_seconds() // 60) if pd and pa else 0))
    duration_actual_min = max(60, int(((aa - ad).total_seconds() // 60) if ad and aa else 0))

    # Distances
    route_nm = live.distanceTotalNm
    route_actual_nm = round(route_nm * 1.005, 1)  # tiny actual deviation

    # Top causes for prompt
    top_causes = ", ".join(f"{f.key} {f.weightPct}%" for f in attribution.factors[:3])

    # AI conclusion — generated by Vertex Pro and cached on the voyage row
    # so the report page becomes cheap on every subsequent visit.
    if voyage.ai_conclusion:
        ai_conclusion = voyage.ai_conclusion
    else:
        prompt = render_prompt(
            "voyage_conclusion", "v1",
            voyage_id=voyage.id,
            origin_name=voyage.origin_name,
            destination_name=voyage.destination_name,
            duration_planned_min=duration_planned_min,
            duration_actual_min=duration_actual_min,
            final_risk_score=final_risk_score,
            cause_breakdown=top_causes,
        )
        parsed, _meta = await call_llm(
            db,
            prompt_name="voyage_conclusion",
            prompt_version="v1",
            prompt_body=prompt,
            schema=_CONCLUSION_SCHEMA,
            note=f"voyage={voyage.id}",
        )
        ai_conclusion = parsed.get("aiConclusion") or (
            "Voyage completed within expected risk band."
        )
        voyage.ai_conclusion = ai_conclusion
        await db.flush()

    summary = (
        f"Voyage from {voyage.origin_name} to {voyage.destination_name}. "
        f"Planned {duration_planned_min} min, actual {duration_actual_min} min "
        f"(delta {duration_actual_min - duration_planned_min:+d} min). "
        f"Final risk score {final_risk_score}."
    )

    return VoyageReport(
        voyage=voyage_out,
        routeNm=route_nm,
        routeActualNm=route_actual_nm,
        durationActualMin=duration_actual_min,
        durationPlannedMin=duration_planned_min,
        summary=summary,
        etaSeries=eta_series,
        events=events,
        alerts=alerts,
        attribution=attribution,
        milestones=milestones,
        finalRiskScore=final_risk_score,
        aiConclusion=ai_conclusion,
    )


async def insight_text(db: AsyncSession, voyage: Voyage) -> dict:
    """Compute a free-form insight paragraph for the analysis page."""
    attribution = await compute_attribution(db, voyage)
    alerts = await list_alerts(db, voyage.id)
    top_causes = ", ".join(f"{f.key} {f.weightPct}%" for f in attribution.factors[:3])
    alerts_text = "; ".join(f"{a.severity}/{a.title}" for a in alerts[:5]) or "no notable alerts"
    live = await compute_live_snapshot(db, voyage)
    pd = _parse_iso(voyage.planned_departure)
    pa = _parse_iso(voyage.planned_arrival) or pd
    ad = _parse_iso(voyage.actual_departure) or pd
    duration_planned_min = max(60, int(((pa - pd).total_seconds() // 60) if pd and pa else 0))
    duration_actual_min = max(duration_planned_min + live.etaDeltaMin, 60)

    prompt = render_prompt(
        "voyage_insight", "v1",
        voyage_id=voyage.id,
        origin_name=voyage.origin_name,
        destination_name=voyage.destination_name,
        duration_planned_min=duration_planned_min,
        duration_actual_min=duration_actual_min,
        final_risk_score=live.riskScore,
        top_causes=top_causes,
        alerts=alerts_text,
    )
    schema = {"type": "object", "properties": {"insight": {"type": "string"}}, "required": ["insight"]}
    parsed, meta = await call_llm(
        db,
        prompt_name="voyage_insight",
        prompt_version="v1",
        prompt_body=prompt,
        schema=schema,
        note=f"voyage={voyage.id}",
    )
    return {"insight": parsed.get("insight", "Voyage progressed within tolerance."), "_meta": meta}
